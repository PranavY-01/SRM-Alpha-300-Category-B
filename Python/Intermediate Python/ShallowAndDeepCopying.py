# Intermediate Python Course | Class 15. Shallow Copying and Deep Copying
# -----------------------------------------------------------------------
# -----------------------------------------------------------------------
# A. Copying Lists
# -----------------------------------------------------------------------

org = [0, 1, 2, 3, 4]
cpy = org

cpy[0] = -10

print(cpy)
print(org)

# -----------------------------------------------------------------------
# Shallow Copying using copy() and slicing
# -----------------------------------------------------------------------

org = [0, 1, 2, 3, 4]
cpy = org.copy()

cpy[0] = -10

print(cpy)
print(org)

org = [0, 1, 2, 3, 4]
cpy = org[:]

# -----------------------------------------------------------------------
# Deep Copying 
# -----------------------------------------------------------------------

import copy

org = [[0, 1, 2, 3], [4, 5, 6, 7]]
cpy = copy.deepcopy(org)

cpy[0][1] = -10

print(cpy)
print(org)

# -----------------------------------------------------------------------
# Difference: Shallow and Deep Copying
# -----------------------------------------------------------------------

import copy

org = [[0, 1, 2], [3, 4, 5]]

shallow = copy.copy(org)
deep = copy.deepcopy(org)

org[0][1] = 100

print("Original:", org)
print("Shallow:", shallow)
print("Deep:", deep)

