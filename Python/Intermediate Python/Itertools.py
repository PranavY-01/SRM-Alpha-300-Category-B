from itertools import *

# -----------------------------------------------------------------------
# A. Product
# ----------------------------------------------------------------------

a = [1, 2]
b = [3, 4]

prod = product(a, b)
print(list(prod))

# -----------------------------------------------------------------------
# B. Permutations
# -----------------------------------------------------------------------

a = [1, 2, 3]

perm = permutations(a)
print(list(perm))

# -----------------------------------------------------------------------
# C. Combinations
# -----------------------------------------------------------------------

a = [1, 2, 3, 4]

comb = combinations(a, 2)
print(list(comb))

# -----------------------------------------------------------------------
# D. Groupby
# -----------------------------------------------------------------------

a = [1, 1, 2, 2, 3, 3, 3]

group_obj = groupby(a)

for key, group in group_obj:
    print(key, list(group))

# -----------------------------------------------------------------------
# E. Infinite Iterators
# -----------------------------------------------------------------------

# Method 1: count
for i in count(10):
    print(i)

    if i == 15:
        break

# Method 2: cycle
a = [1, 2, 3]

for i in cycle(a):
    print(i)

    if i == 3:
        break

# Method 3: repeat
for i in repeat(1, 4):
    print(i)

