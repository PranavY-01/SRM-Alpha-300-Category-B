# -----------------------------------------------------------------------
# A. Using the *args and **kwargs syntax
# -----------------------------------------------------------------------

def foo(a, b, *args, **kwargs):
    print(a, b)
    print(args)
    print(kwargs)

foo(1, 2, 3, 4, 5, six=6, seven=7)

def foo2(a, b, *, c):
    print(a, b, c)

foo2(1, 2, c=3)

# -----------------------------------------------------------------------
# B. Unpacking Dictionaries
# -----------------------------------------------------------------------

def foo3(a, b, c):
    print(a, b, c)

my_dict = {'a': 1, 'b': 2, 'c': 3}

foo3(**my_dict)

# -----------------------------------------------------------------------
# C. Merging Containers
# -----------------------------------------------------------------------

my_tuple = (1, 2, 3)
my_list = [4, 5, 6]

new_list = [*my_tuple, *my_list]

print(new_list)

dict_a = {'a': 1, 'b': 2}
dict_b = {'c': 3, 'd': 4}

my_dict = {**dict_a, **dict_b}

print(my_dict)

